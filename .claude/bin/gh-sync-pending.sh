#!/usr/bin/env bash
# gh-sync-pending.sh — sync pending DoD confirmations to GitHub Issues/PRs
# Idempotent: re-running won't create duplicate issues
set -euo pipefail

ROOT="$(git -C "$(dirname "$0")/../.." rev-parse --show-toplevel 2>/dev/null || echo ".")"
AUDIT_FILE="$ROOT/.audit/events.jsonl"
PENDING_FILE="$ROOT/.dod/pending-confirmations.md"

command -v gh >/dev/null || { echo "[gh-sync] ERROR: gh CLI not installed" >&2; exit 1; }

# Parse pending items from audit log
pending_json=$(python3 - <<PYEOF
import json, sys

pending = {}
confirmed = set()

try:
    with open('${AUDIT_FILE}') as f:
        for line in f:
            line = line.strip()
            if not line: continue
            ev = json.loads(line)
            et = ev.get('event','')
            if et == 'ac.evidence_ready':
                ac_id = ev.get('ac_id','')
                if ac_id: pending[ac_id] = ev
            elif et in ('ac.confirmed','ac.rejected'):
                ac_id = ev.get('ac_id','')
                if ac_id: confirmed.add(ac_id)
except FileNotFoundError:
    pass

result = [v for k,v in pending.items() if k not in confirmed]
print(json.dumps(result))
PYEOF
)

count=$(echo "$pending_json" | python3 -c "import sys,json; print(len(json.load(sys.stdin)))")
echo "[gh-sync] Found ${count} pending AC confirmation(s)" >&2

if [[ "$count" == "0" ]]; then exit 0; fi

echo "$pending_json" | python3 - <<PYEOF
import json, subprocess, sys

items = json.load(sys.stdin)
for item in items:
    ac_id    = item.get('ac_id', 'unknown')
    sprint   = item.get('sprint', '?')
    milestone = item.get('milestone', '?')
    evidence = item.get('evidence', {})
    seq      = item.get('seq', '?')

    title = f"DoD Review: {ac_id} — Sprint {sprint}"

    # Check if issue already exists
    check = subprocess.run(
        ['gh', 'issue', 'list', '--label', f'dod:ac', '--search', ac_id, '--json', 'number,title'],
        capture_output=True, text=True
    )
    existing = json.loads(check.stdout or '[]')
    if existing:
        print(f"[gh-sync] Issue exists for {ac_id}: #{existing[0]['number']}", file=sys.stderr)
        continue

    body = f"""## DoD Confirmation Required

**AC ID**: {ac_id}
**Sprint**: {sprint}
**Milestone**: {milestone}
**Audit seq**: #{seq}

## Evidence

| Signal | Status |
|--------|--------|
"""
    for k, v in evidence.items():
        status = "✅" if v else "❌"
        body += f"| {k} | {status} {v} |\n"

    body += """
## How to respond

Add a comment with one of:
- `/confirm [optional comment]` — AC is satisfied
- `/reject <reason>` — AC failed, describe what's missing
- `/needs-more <description>` — need additional evidence

---
_Generated by sprint-system audit chain_
"""

    labels = ['dod:pending', 'dod:ac', f'dod:milestone:{milestone}', f'dod:sprint:{sprint}']

    cmd = ['gh', 'issue', 'create',
           '--title', title,
           '--body', body]
    for label in labels:
        cmd += ['--label', label]

    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode == 0:
        print(f"[gh-sync] Created issue for {ac_id}: {result.stdout.strip()}", file=sys.stderr)
    else:
        print(f"[gh-sync] ERROR creating issue for {ac_id}: {result.stderr}", file=sys.stderr)
PYEOF
